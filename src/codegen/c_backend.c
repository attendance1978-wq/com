#include "codegen/codegen.h"
#include "util/string.h"

#include <limits.h>
#include <stdlib.h>

static void put_literal(StrBuf *sb, long v) {
    if (v == LONG_MIN) sb_puts(sb, "(-9223372036854775807L - 1)");
    else sb_printf(sb, "%ldL", v);
}

char *emit_c(const IR *ir, int nvars) {
    StrBuf sb;
    sb_init(&sb);
    int n = ir->count;
    char *target = calloc((size_t)n + 1, 1);

    for (int i = 0; target && i < n; i++) {
        OpCode op = ir->code[i].op;
        long a = ir->code[i].arg;
        if ((op == OP_JMP || op == OP_JZ) && a >= 0 && a <= n) target[a] = 1;
    }

    sb_puts(&sb, "/* generated by com */\n#include <stdio.h>\n\n");
    sb_printf(&sb, "static long v[%d];\n\n", nvars > 0 ? nvars : 1);
    sb_puts(&sb, "int main(void) {\n"
                 "    long s[4096];\n"
                 "    int sp = 0;\n"
                 "    long a, b;\n"
                 "    (void)s; (void)sp; (void)a; (void)b; (void)v;\n\n");

    for (int i = 0; i < n; i++) {
        const Instr *in = &ir->code[i];
        if (target && target[i]) sb_printf(&sb, "L%d:;\n", i);
        switch (in->op) {
        case OP_NOP: break;
        case OP_PUSH:
            sb_puts(&sb, "    s[sp++] = ");
            put_literal(&sb, in->arg);
            sb_puts(&sb, ";\n");
            break;
        case OP_LOAD:  sb_printf(&sb, "    s[sp++] = v[%ld];\n", in->arg); break;
        case OP_STORE: sb_printf(&sb, "    v[%ld] = s[--sp];\n", in->arg); break;
        case OP_ADD:
            sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = (long)((unsigned long)a + (unsigned long)b);\n");
            break;
        case OP_SUB:
            sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = (long)((unsigned long)a - (unsigned long)b);\n");
            break;
        case OP_MUL:
            sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = (long)((unsigned long)a * (unsigned long)b);\n");
            break;
        case OP_DIV:
            sb_puts(&sb, "    b = s[--sp]; a = s[--sp];\n"
                         "    if (b == 0) { fputs(\"error: division by zero\\n\", stderr); return 1; }\n"
                         "    s[sp++] = (b == -1) ? (long)(0UL - (unsigned long)a) : a / b;\n");
            break;
        case OP_MOD:
            sb_puts(&sb, "    b = s[--sp]; a = s[--sp];\n"
                         "    if (b == 0) { fputs(\"error: division by zero\\n\", stderr); return 1; }\n"
                         "    s[sp++] = (b == -1) ? 0 : a % b;\n");
            break;
        case OP_LT: sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = a < b;\n"); break;
        case OP_GT: sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = a > b;\n"); break;
        case OP_EQ: sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = a == b;\n"); break;
        case OP_NE: sb_puts(&sb, "    b = s[--sp]; a = s[--sp]; s[sp++] = a != b;\n"); break;
        case OP_PRINT:  sb_puts(&sb, "    printf(\"%ld\\n\", s[--sp]);\n"); break;
        case OP_PRINTC: sb_puts(&sb, "    putchar((int)(unsigned char)s[--sp]);\n"); break;
        case OP_JMP: sb_printf(&sb, "    goto L%ld;\n", in->arg); break;
        case OP_JZ:  sb_printf(&sb, "    if (s[--sp] == 0) goto L%ld;\n", in->arg); break;
        case OP_HALT: sb_puts(&sb, "    return 0;\n"); break;
        default: break;
        }
    }
    if (target && target[n]) sb_printf(&sb, "L%d:;\n", n);
    sb_puts(&sb, "    return 0;\n}\n");
    free(target);
    return sb_take(&sb);
}
